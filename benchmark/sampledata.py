"""Synthetic development data, for exercising the analytics stack only.

Everything this module writes is stamped ``run_kind = 'development_sample'``
and carries agent names that begin with ``sample-``. It exists so the SQL
suite and the dashboard can be built and reviewed before any real agent run
exists -- not to stand in for one.

**These numbers are invented.** They must never appear in a claim about any
real agent, and the integrity audit reports their presence explicitly.
"""

from __future__ import annotations

import random
from dataclasses import dataclass

from .failures import FailureCategory
from .storage import ResultsStore, utc_now
from .tasks import Task, load_tasks

SAMPLE_LABEL = "SYNTHETIC DEVELOPMENT DATA - NOT A MEASUREMENT"
SAMPLE_NOTES = (
    "Generated by benchmark.sampledata to exercise the analytics stack. "
    "Every value here is invented. Excluded from every 'measurement' query."
)


@dataclass(frozen=True)
class SampleAgent:
    """A fictional agent profile: how often it succeeds and how it fails."""

    agent: str
    model: str
    #: Probability of passing a task of each difficulty.
    skill: dict[str, float]
    mean_seconds: float
    cost_per_attempt: float
    #: Weights over the failure modes this fictional agent tends to exhibit.
    failure_weights: dict[FailureCategory, float]


SAMPLE_AGENTS = (
    SampleAgent(
        agent="sample-agent-alpha",
        model="synthetic-large",
        skill={"easy": 0.85, "medium": 0.6, "hard": 0.35},
        mean_seconds=95.0,
        cost_per_attempt=0.42,
        failure_weights={
            FailureCategory.INCOMPLETE_IMPLEMENTATION: 0.35,
            FailureCategory.UNDER_EDITING: 0.15,
            FailureCategory.REGRESSION: 0.15,
            FailureCategory.HALLUCINATED_API: 0.1,
            FailureCategory.WRONG_LOCATION: 0.1,
            FailureCategory.OVER_EDITING: 0.08,
            FailureCategory.TIMEOUT: 0.04,
            FailureCategory.TEST_GAMING: 0.03,
        },
    ),
    SampleAgent(
        agent="sample-agent-beta",
        model="synthetic-small",
        skill={"easy": 0.7, "medium": 0.4, "hard": 0.15},
        mean_seconds=48.0,
        cost_per_attempt=0.11,
        failure_weights={
            FailureCategory.INCOMPLETE_IMPLEMENTATION: 0.3,
            FailureCategory.UNDER_EDITING: 0.25,
            FailureCategory.WRONG_LOCATION: 0.15,
            FailureCategory.HALLUCINATED_API: 0.12,
            FailureCategory.REGRESSION: 0.1,
            FailureCategory.OVER_EDITING: 0.05,
            FailureCategory.TIMEOUT: 0.03,
        },
    ),
)


def _pick_failure(rng: random.Random, weights: dict[FailureCategory, float]) -> FailureCategory:
    categories = list(weights)
    return rng.choices(categories, weights=[weights[c] for c in categories], k=1)[0]


def _synthesise_attempt(
    rng: random.Random, profile: SampleAgent, task: Task, attempt_index: int
) -> dict:
    passed = rng.random() < profile.skill.get(task.difficulty, 0.4)
    tests_total = 8 + len(task.acceptance_criteria) * 2

    if passed:
        status, failure = "passed", FailureCategory.NONE
        tests_passed, regressions = tests_total, 0
    else:
        failure = _pick_failure(rng, profile.failure_weights)
        regressions = rng.randint(1, 3) if failure is FailureCategory.REGRESSION else 0
        if failure is FailureCategory.TIMEOUT:
            status, tests_passed = "timeout", 0
        elif failure is FailureCategory.TEST_GAMING:
            status, tests_passed = "tampered", 0
        else:
            status = "failed"
            ceiling = max(1, tests_total - 1)
            tests_passed = 0 if failure is FailureCategory.UNDER_EDITING else rng.randint(0, ceiling)

    if failure is FailureCategory.UNDER_EDITING:
        files_changed, lines_added, lines_deleted = 0, 0, 0
    elif failure is FailureCategory.OVER_EDITING:
        files_changed = rng.randint(6, 14)
        lines_added, lines_deleted = rng.randint(200, 600), rng.randint(100, 400)
    else:
        files_changed = max(1, len(task.expected_files) + rng.randint(-1, 1))
        lines_added, lines_deleted = rng.randint(5, 80), rng.randint(0, 40)

    seconds = max(
        3.0,
        rng.gauss(profile.mean_seconds * (2.5 if status == "timeout" else 1.0), profile.mean_seconds / 3),
    )
    return {
        "task": task,
        "attempt_index": attempt_index,
        "status": status,
        "passed": 1 if passed else 0,
        "tampered": 1 if status == "tampered" else 0,
        "failure_category": str(failure),
        "tests_total": tests_total,
        "tests_passed": tests_passed,
        "baseline_passed": max(0, tests_total // 3),
        "regressions": regressions,
        "files_changed": files_changed,
        "lines_added": lines_added,
        "lines_deleted": lines_deleted,
        "expected_files_touched": min(len(task.expected_files), files_changed),
        "tool_calls": rng.randint(4, 40),
        "num_turns": rng.randint(2, 18),
        "cost_usd": round(profile.cost_per_attempt * rng.uniform(0.5, 1.8), 4),
        "human_interventions": 1 if rng.random() < 0.05 else 0,
        "total_duration_ms": int(seconds * 1000),
    }


def seed_sample_data(
    store: ResultsStore, *, attempts_per_task: int = 3, seed: int = 20260909
) -> list[str]:
    """Populate ``store`` with clearly-labelled synthetic runs.

    Returns the run uids created. Deterministic for a given seed, so the
    dashboard a reviewer sees matches the one described in the docs.
    """
    rng = random.Random(seed)
    tasks = load_tasks()
    if not tasks:
        raise ValueError("no tasks registered; cannot synthesise sample data")
    store.register_tasks(tasks)

    run_uids: list[str] = []
    for profile in SAMPLE_AGENTS:
        run_id, run_uid = store.start_run(
            adapter="sample",
            agent=profile.agent,
            model=profile.model,
            adapter_version="sample/1.0",
            attempts_per_task=attempts_per_task,
            run_kind="development_sample",
            # Synthetic rows describe no real boundary, so they claim none.
            isolation_backend="synthetic",
            isolation_version="n/a",
            isolation_active=False,
            publishable=False,
            network_policy="n/a",
            label=SAMPLE_LABEL,
            notes=SAMPLE_NOTES,
        )
        run_uids.append(run_uid)

        for task in tasks:
            for index in range(1, attempts_per_task + 1):
                record = _synthesise_attempt(rng, profile, task, index)
                attempt_id = store.record_attempt(
                    run_id=run_id,
                    task_id=task.id,
                    task_fingerprint=task.spec_fingerprint(),
                    attempt_index=record["attempt_index"],
                    status=record["status"],
                    passed=record["passed"],
                    tampered=record["tampered"],
                    failure_category=record["failure_category"],
                    classification_source="auto",
                    reason="synthetic development sample",
                    tests_total=record["tests_total"],
                    tests_passed=record["tests_passed"],
                    baseline_passed=record["baseline_passed"],
                    regressions=record["regressions"],
                    files_changed=record["files_changed"],
                    lines_added=record["lines_added"],
                    lines_deleted=record["lines_deleted"],
                    expected_files_touched=record["expected_files_touched"],
                    tool_calls=record["tool_calls"],
                    num_turns=record["num_turns"],
                    cost_usd=record["cost_usd"],
                    human_interventions=record["human_interventions"],
                    fixture_hash=task.spec_fingerprint(),
                    isolation_active=0,
                    network_policy="n/a",
                    started_at=utc_now(),
                    finished_at=utc_now(),
                    verify_exit_code=0 if record["passed"] else 1,
                    verify_duration_ms=int(record["total_duration_ms"] * 0.2),
                    agent_duration_ms=int(record["total_duration_ms"] * 0.8),
                    total_duration_ms=record["total_duration_ms"],
                    protected_hash_before="sample",
                    protected_hash_after="sample" if not record["tampered"] else "sample-modified",
                    workspace_hash_before="sample-before",
                    workspace_hash_after=(
                        "sample-before" if record["files_changed"] == 0 else "sample-after"
                    ),
                    notes=SAMPLE_NOTES,
                )
                store.record_tests(attempt_id, _synthesise_tests(rng, task, record))
        store.finish_run(run_id)
    return run_uids


def _synthesise_tests(rng: random.Random, task: Task, record: dict) -> list[tuple]:
    """Per-test rows consistent with the attempt's headline counts."""
    rows: list[tuple] = []
    hidden_from = record["tests_total"] // 2 if task.has_hidden_tests else record["tests_total"]
    for index in range(record["tests_total"]):
        satisfied = index < record["tests_passed"]
        rows.append(
            (
                f"tests.test_{task.id.replace('-', '_')}.T.test_{index:02d}",
                "passed" if satisfied else rng.choice(["failed", "error"]),
                1 if index < record["baseline_passed"] else 0,
                1 if index >= hidden_from else 0,
            )
        )
    return rows
